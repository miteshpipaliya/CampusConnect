import sharp from 'sharp';
import {mkdir,rename} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {dirname,join} from 'node:path';
const root=fileURLToPath(new URL('../',import.meta.url));
const output=join(root,'public/rewards/hoodie-2k.webp');
await mkdir(dirname(output),{recursive:true});
const source=join(root,'assets/rewards/hoodie-original.png');
const temp=output+'.tmp';
await sharp(source).flatten({background:'#ffffff'}).resize(1856,1856,{fit:'contain',position:'centre',background:'#ffffff',kernel:'lanczos3'}).extend({top:96,bottom:96,left:96,right:96,background:'#ffffff'}).webp({quality:93,effort:6}).toFile(temp);
await rename(temp,output);
const metadata=await sharp(output).metadata();
if(metadata.width!==2048||metadata.height!==2048)throw Error('Hoodie reward image must be 2048 x 2048');
console.log('Prepared first-place hoodie reward: 2048 x 2048 WebP');
